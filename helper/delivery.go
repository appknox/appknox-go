const (
	autofixBranchPrefix = "appknox-autofix/"
	// GitHub refs are limited to ~244 bytes including "refs/heads/".
	gitHubRefMaxBytes = 244
	refsHeadsPrefix   = "refs/heads/"
)

var (
	errNeedHeadRef = errors.New("autofix needs --head-ref (or GITHUB_HEAD_REF / GITHUB_REF refs/heads/…)")
	errForkPR      = errors.New("autofix does not support fork PRs (cannot push the head)")
	disallowedHead = regexp.MustCompile(`[^A-Za-z0-9._/-]+`)
)

// Delivery is the GitHub push outcome recorded on Appknox after autofix.
type Delivery struct {
	URL       string
	Branch    string
	Base      string
	CommitSHA string
	PRCreated bool // true when GitHub opened a new PR; false when an open PR was reused
}

// deliverBranch pushes patched files to a new branch, opens a GitHub PR, and
// returns the PR URL for Mycroft's KnoxIQ AutofixPR row.
func deliverBranch(ctx context.Context, opts AutofixOptions, patches []filePatch) (Delivery, error) {
	opts = applyCIDefaults(opts)
	if forkPRFromCI() {
		return Delivery{}, errForkPR
	}
	owner, name, err := splitRepo(opts.Repo)
	if err != nil {
		return Delivery{}, errors.New("autofix needs a CI repo (GITHUB_REPOSITORY) to push the fix branch")
	}
	token := firstNonEmpty(opts.GithubToken, os.Getenv("GITHUB_TOKEN"))
	if token == "" {
		return Delivery{}, errors.New("autofix needs a GitHub token (--github-token or GITHUB_TOKEN) to push the fix branch")
	}
	branch, err := prBranch(opts.HeadRef)
	if err != nil {
		return Delivery{}, err
	}
	files := make([]ghpr.FileChange, len(patches))
	for i, p := range patches {
		files[i] = ghpr.FileChange{Path: p.Path, Content: p.Content}
	}
	cfg := ghpr.Config{Owner: owner, Repo: name, BaseRef: opts.Ref, Token: token, APIBase: os.Getenv("GITHUB_API_URL")}
	res, err := ghpr.PushFiles(ctx, cfg, branch, files, prTitle(opts))
	if err != nil {
		return Delivery{}, err
	}
	prURL, created, err := ghpr.OpenPullRequest(ctx, cfg, res.Base, res.Branch, prTitle(opts), prBody(opts, patches))
	if err != nil {
		return Delivery{}, fmt.Errorf("pushed branch %s but failed to open a pull request: %w\nGITHUB_TOKEN cannot open PRs unless the workflow has pull-requests: write and the repo allows Actions to create PRs (Settings → Actions → General). Or set APPKNOX_GITHUB_TOKEN to a PAT with repo scope", res.Branch, err)
	}
	return Delivery{URL: prURL, Branch: res.Branch, Base: res.Base, CommitSHA: res.CommitSHA, PRCreated: created}, nil
}

func prTitle(opts AutofixOptions) string {
	if opts.PRTitle != "" {
		return opts.PRTitle
	}
	if opts.HeadRef != "" {
		return "fix(autofix): " + strings.TrimSpace(opts.HeadRef)
	}
	return "fix(autofix): security findings"
}

func prBody(opts AutofixOptions, patches []filePatch) string {
	if opts.PRBody != "" {
		return opts.PRBody
	}
	return renderAutofixPRBody(nil, patches, "")
}

const (
	prProductName      = "Appknox Intelligent Fixer"
	prLogoURL          = "https://raw.githubusercontent.com/appknox/press-kit/master/logo/logo-dark-small.png"
	prTagline          = "AI-powered security remediation by KnoxIQ"
	prSummaryHeading   = "Appknox has proposed fixes for security vulnerabilities"
	prSummaryText      = "This PR contains code changes generated by Appknox Intelligent Fixer to remediate vulnerabilities identified in your application scan. Review the changes and run your tests before merging."
	prCountsNote       = "Counts are based on this run's reported remediation results, not a verified current scan."
	prVerificationStep = "Upload the resulting binary to Appknox and rescan to verify remediation."
	prReviewDisclaimer = "AI-generated changes require developer review. A proposed fix does not by itself prove that a vulnerability is resolved."
	prNoneUnaddressed  = "No findings were left unaddressed in this run."
	prNoneAddressed    = "No vulnerabilities were changed in this run."
)

// renderAutofixPRBody is the pull-request description written to GitHub.
// Addressed and unaddressed rows follow the run: any number of findings, one
// row or line each.
func renderAutofixPRBody(findings []findingOutcome, patches []filePatch, truncated string) string {
	addressed, notAddressed, addressedCount, notCount := prFindingTables(findings, patches)
	var b strings.Builder
	fmt.Fprintf(&b, "# %s <img src=\"%s\" alt=\"Appknox\" align=\"right\" height=\"40\">\n\n**%s**\n\n## %s\n\n%s\n\n",
		prProductName, prLogoURL, prTagline, prSummaryHeading, prSummary(truncated))
	b.WriteString("| Findings addressed | Not addressed |\n|---:|---:|\n")
	fmt.Fprintf(&b, "| **%d** | **%d** |\n\n*%s*\n\n---\n\n", addressedCount, notCount, prCountsNote)
	b.WriteString("## Vulnerabilities addressed by the proposed changes\n\n")
	if len(addressed) == 0 {
		b.WriteString(prNoneAddressed)
		b.WriteString("\n")
	} else {
		b.WriteString("| Vulnerability | Severity | Files changed |\n|---|---|---|\n")
		for _, row := range addressed {
			fmt.Fprintf(&b, "| %s | %s | %s |\n", prCell(row.name), prCell(row.severity), prFilesCell(row.files))
		}
	}
	b.WriteString("\n---\n\n## Findings not addressed\n\n")
	b.WriteString("- Some findings may be false positives.\n")
	b.WriteString("- Some fixes may require manual intervention.\n")
	b.WriteString("- Some changes may be rejected by the remediation safety checks.\n\n")
	if len(notAddressed) == 0 {
		b.WriteString(prNoneUnaddressed)
		b.WriteString("\n")
	} else {
		for _, f := range notAddressed {
			fmt.Fprintf(&b, "- **%s**%s: %s\n",
				prCell(findingLabel(f)), prSeveritySuffix(f.Severity),
				prCell(firstNonEmpty(f.Detail, "No change was made.")))
		}
	}
	fmt.Fprintf(&b, "\n---\n\n## Before merging\n\n- Review the proposed changes.\n- Run the build and automated tests.\n- %s\n\n> %s\n",
		prVerificationStep, prReviewDisclaimer)
	return b.String()
}

type prVulnRow struct {
	name     string
	severity string
	files    []string
}

func prSummary(truncated string) string {
	if note := strings.TrimSpace(truncated); note != "" {
		return prSummaryText + " " + note
	}
	return prSummaryText
}

func prSeveritySuffix(severity string) string {
	severity = prCell(severity)
	if severity == "—" {
		return ""
	}
	return " (" + severity + ")"
}

func prFindingTables(findings []findingOutcome, patches []filePatch) (addressed []prVulnRow, notAddressed []findingOutcome, addressedCount, notCount int) {
	index := map[string]int{}
	add := func(name, severity, path string) {
		name = strings.TrimSpace(name)
		if name == "" {
			name = "Security finding"
		}
		i, ok := index[name]
		if !ok {
			index[name] = len(addressed)
			addressed = append(addressed, prVulnRow{name: name, severity: severity})
			i = len(addressed) - 1
		}
		if addressed[i].severity == "" && severity != "" {
			addressed[i].severity = severity
		}
		if path == "" {
			return
		}
		for _, have := range addressed[i].files {
			if have == path {
				return
			}
		}
		addressed[i].files = append(addressed[i].files, path)
	}

	tracked := false
	for _, f := range findings {
		switch f.Status {
		case statusFixed, statusPartial:
			tracked = true
			addressedCount++
			add(firstNonEmpty(f.Finding, f.Title), f.Severity, "")
		case statusSkipped:
			tracked = true
			notCount++
			notAddressed = append(notAddressed, f)
		}
	}
	for _, p := range patches {
		names := splitPatchFindings(p.Finding)
		if len(names) == 0 {
			names = []string{""}
		}
		matched := false
		for _, name := range names {
			keys := matchingVulns(index, name)
			if len(keys) == 0 {
				continue
			}
			matched = true
			for _, key := range keys {
				add(key, "", p.Path)
			}
		}
		if matched {
			continue
		}
		for _, name := range names {
			add(name, "", p.Path)
		}
	}
	if !tracked {
		addressedCount = len(addressed)
	}
	return addressed, notAddressed, addressedCount, notCount
}

func matchingVulns(index map[string]int, name string) []string {
	name = strings.TrimSpace(name)
	if name == "" {
		return nil
	}
	if _, ok := index[name]; ok {
		return []string{name}
	}
	var keys []string
	for key := range index {
		if strings.Contains(name, key) || strings.Contains(key, name) {
			keys = append(keys, key)
		}
	}
	return keys
}

func splitPatchFindings(finding string) []string {
	if strings.TrimSpace(finding) == "" {
		return nil
	}
	var out []string
	for _, part := range strings.Split(finding, "; ") {
		part = strings.TrimSpace(part)
		if part != "" {
			out = append(out, part)
		}
	}
	return out
}

func findingLabel(f findingOutcome) string {
	switch {
	case f.Title != "" && f.Finding != "" && f.Title != f.Finding:
		return f.Finding + " / " + f.Title
	case f.Title != "":
		return f.Title
	case f.Finding != "":
		return f.Finding
	default:
		return "Finding"
	}
}

func prCell(s string) string {
	s = strings.TrimSpace(s)
	s = strings.ReplaceAll(s, "\r\n", " ")
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "|", "\\|")
	if s == "" {
		return "—"
	}
	return s
}

func prFilesCell(paths []string) string {
	if len(paths) == 0 {
		return "—"
	}
	parts := make([]string, 0, len(paths))
	for _, p := range paths {
		p = strings.TrimSpace(strings.ReplaceAll(p, "`", ""))
		p = strings.ReplaceAll(p, "|", "\\|")
		if p == "" {
			continue
		}
		parts = append(parts, "`"+p+"`")
	}
	if len(parts) == 0 {
		return "—"
	}
	return strings.Join(parts, ", ")
}

// reportAutofixPR POSTs the pushed branch to KnoxIQ so the dashboard can list it.
// Skipped when --file-id is not set (manual --finding has nothing to attach to).
func reportAutofixPR(ctx context.Context, opts AutofixOptions, d Delivery, patches []filePatch) error {
	return reportAutofixPRWith(ctx, getClient(), opts, d, patches)
}

func reportAutofixPRWith(ctx context.Context, client *appknox.Client, opts AutofixOptions, d Delivery, patches []filePatch) error {
	if opts.FileID <= 0 {
		return nil
	}
	_, _, err := client.KnoxIQ.CreateAutofixPR(ctx, opts.FileID, buildAutofixPR(opts, d, patches))
	return err
}

func buildAutofixPR(opts AutofixOptions, d Delivery, patches []filePatch) *appknox.AutofixPR {
	paths := make([]string, len(patches))
	for i, p := range patches {
		paths[i] = p.Path
	}
	base := d.Base
	if base == "" {
		base = opts.Ref
	}
	return &appknox.AutofixPR{
		Repo:           opts.Repo,
		BaseBranch:     base,
		Branch:         d.Branch,
		PRURL:          d.URL,
		CommitSHA:      d.CommitSHA,
		PatchedFiles:   paths,
		AutofixRequest: opts.JobID,
	}
}

// prBranch is a stable GitHub head for every file id on the same feature branch.
func prBranch(headRef string) (string, error) {
	feature, err := sanitizeFeature(headRef)
	if err != nil {
		return "", err
	}
	return capGitRef(autofixBranchPrefix+feature, headRef), nil
}

func sanitizeFeature(headRef string) (string, error) {
	headRef = strings.TrimSpace(headRef)
	if headRef == "" {
		return "", errNeedHeadRef
	}
	replaced := disallowedHead.ReplaceAllString(headRef, "-")
	var kept []string
	for _, part := range strings.Split(replaced, "/") {
		part = strings.Trim(part, ".")
		if part == "" || part == "." || part == ".." {
			continue
		}
		for strings.Contains(part, "..") {
			part = strings.ReplaceAll(part, "..", ".")
		}
		part = strings.Trim(part, ".")
		if part == "" {
			continue
		}
		kept = append(kept, part)
	}
	out := strings.Join(kept, "/")
	if out == "" {
		return "", fmt.Errorf("illegal feature branch name %q", headRef)
	}
	return out, nil
}

// capGitRef truncates a branch name to GitHub's ref limit, keeping uniqueness
// with a short hash of the original feature name.
func capGitRef(branch, original string) string {
	max := gitHubRefMaxBytes - len(refsHeadsPrefix)
	if len(branch) <= max {
		return branch
	}
	sum := sha256.Sum256([]byte(original))
	suffix := "-" + hex.EncodeToString(sum[:4])
	keep := max - len(suffix)
	if keep < 1 {
		return suffix[1:]
	}
	truncated := strings.TrimRight(branch[:keep], "/.-")
	if truncated == "" {
		truncated = strings.TrimRight(autofixBranchPrefix, "/")
	}
	return truncated + suffix
}

// commitMessage is a conventional-commit subject for the fix.
func commitMessage(p filePatch) string {
	name := p.Finding
	if name == "" {
		name = "security finding"
	}
	return fmt.Sprintf("fix(autofix): %s in %s", name, filepath.Base(p.Path))
}
